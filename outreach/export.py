"""STAGE 8: write the result files (CSV + Markdown) into the data folder."""
import csv
import logging

from . import storage
from .utils import NOT_AVAILABLE, NOT_FOUND

log = logging.getLogger("export")


def write_csv(path, header, rows):
    # utf-8-sig makes the file open correctly in Excel
    with open(path, "w", newline="", encoding="utf-8-sig") as file:
        writer = csv.writer(file)
        writer.writerow(header)
        writer.writerows(rows)


def join_list(value):
    if isinstance(value, list):
        return "; ".join(value)
    return value or ""


def show_rate(rate):
    return NOT_AVAILABLE if rate is None else str(rate) + "%"


def status_reason(channel):
    """Short explanation of why a channel passed or failed."""
    if channel["filter_status"] == "passed":
        return "Passed all checks"
    failed = []
    for reason in channel.get("filter_reasons") or []:
        if reason.startswith("FAIL "):
            failed.append(reason[5:])
    return " | ".join(failed) or "Not evaluated"


def export_dataset(cfg, conn, folder):
    """Every discovered creator, with pass/fail status and the reason."""
    rows = []
    for c in storage.fetch(conn, "SELECT * FROM influencers ORDER BY filter_status DESC, fit_score DESC, followers DESC"):
        if c["email"]:
            email = c["email"]
        elif c["filter_status"] == "passed":
            email = NOT_FOUND
        else:
            email = "Not Checked"
        rows.append([
            c["name"], c["platform"], "Hidden" if c["followers"] is None else c["followers"],
            show_rate(c["engagement_rate"]), cfg["niche"]["name"], email, c["profile_url"],
            join_list(c["content_themes"] or c["sub_niches"]), c["filter_status"], status_reason(c),
            c["country"] or NOT_AVAILABLE, c["tier"] or "", c["content_relevance"], c["fit_score"],
            c["discovered_via"], " | ".join(c["filter_reasons"] or []),
        ])
    path = folder / "influencers_all.csv"
    write_csv(path, ["Name", "Platform", "Followers", "Engagement", "Niche", "Email", "Profile URL", "Content Theme",
                     "Status", "Status Reason", "Country", "Tier", "Content Relevance %", "Fit Score",
                     "Discovered Via", "All Checks"], rows)
    return path


def export_shortlist(cfg, conn, folder):
    """Creators that passed, with all enrichment fields."""
    rows = []
    for c in storage.fetch(conn, "SELECT * FROM influencers WHERE filter_status = 'passed' ORDER BY fit_score DESC"):
        rows.append([
            c["name"], c["platform"], c["profile_url"], c["followers"], show_rate(c["engagement_rate"]),
            cfg["niche"]["name"], join_list(c["sub_niches"]), join_list(c["content_themes"]), c["content_tone"] or "",
            c["email"] or NOT_FOUND, c["email_source"] or "", c["instagram"] or NOT_FOUND, c["tiktok"] or NOT_FOUND,
            c["website"] or NOT_FOUND, c["audience_age"] or NOT_AVAILABLE, c["audience_gender"] or NOT_AVAILABLE,
            c["audience_geo"] or NOT_AVAILABLE, c["avg_views"], (c["last_upload_at"] or "")[:10], c["fit_score"],
            c["channel_id"],
        ])
    path = folder / "shortlisted_enriched.csv"
    write_csv(path, ["Influencer Name", "Platform", "Profile URL", "Follower Count", "Engagement Rate",
                     "Category / Niche", "Sub-niches", "Content Themes", "Content Tone", "Contact Email",
                     "Email Source", "Instagram", "TikTok", "Website", "Audience Age", "Audience Gender",
                     "Audience Geography", "Avg Views (recent)", "Last Upload", "Fit Score", "Channel ID"], rows)
    return path


def load_messages(conn):
    return storage.fetch(conn,
        "SELECT i.name, i.profile_url, i.email, m.* FROM messages m "
        "JOIN influencers i ON i.channel_id = m.channel_id ORDER BY i.fit_score DESC")


def export_messages(conn, folder):
    """The generated email and DM for each shortlisted creator, as CSV and as readable Markdown."""
    messages = load_messages(conn)

    rows = []
    for m in messages:
        rows.append([
            m["name"], m["email"] or NOT_FOUND, m["collab_angle"], m["email_subject"], m["email_body"],
            m["email_words"], m["instagram_dm"], m["dm_words"], m["generated_by"], m["model"] or "",
            "yes" if m["needs_review"] else "no", "yes" if m["approved"] else "no",
            join_list((m["signals"] or {}).get("referenced")), m["channel_id"],
        ])
    csv_path = folder / "messages.csv"
    write_csv(csv_path, ["Influencer", "Email", "Collaboration Angle", "Email Subject", "Email Body", "Email Words",
                         "Instagram DM", "DM Words", "Generated By", "Model", "Needs Review", "Approved",
                         "Signals Referenced", "Channel ID"], rows)

    md_path = folder / "messages.md"
    with open(md_path, "w", encoding="utf-8") as file:
        file.write("# Personalised outreach messages (" + str(len(messages)) + " creators)\n\n")
        for m in messages:
            written_by = m["generated_by"] + (" / " + m["model"] if m["model"] else "")
            if m["needs_review"]:
                written_by += " (needs review)"
            file.write("## " + m["name"] + "\n\n")
            file.write("- Profile: " + m["profile_url"] + "\n")
            file.write("- Email: " + (m["email"] or NOT_FOUND) + "\n")
            file.write("- Angle: " + m["collab_angle"] + "\n")
            file.write("- Written by: " + written_by + "\n\n")
            file.write("**Email (" + str(m["email_words"]) + " words)** - Subject: " + m["email_subject"] + "\n\n")
            for line in m["email_body"].splitlines():
                file.write("> " + line + "\n")
            file.write("\n**Instagram DM (" + str(m["dm_words"]) + " words)**\n\n> " + m["instagram_dm"] + "\n\n---\n\n")
    return csv_path, md_path


def export_tracker(conn, folder):
    """One line per shortlisted creator: was the email sent, when, and with what result."""
    rows = []
    for m in load_messages(conn):
        email_logs = storage.fetch(conn, "SELECT * FROM outreach_log WHERE channel_id = ? AND channel_type = 'email' "
                                         "ORDER BY id DESC LIMIT 1", (m["channel_id"],))
        dm_logs = storage.fetch(conn, "SELECT status FROM outreach_log WHERE channel_id = ? "
                                      "AND channel_type = 'instagram_dm' ORDER BY id DESC LIMIT 1", (m["channel_id"],))
        if email_logs:
            last = email_logs[0]
            sent = {"sent": "Yes", "simulated": "Simulated"}.get(last["status"], "No")
            status = last["status"] + ": " + last["detail"]
            date, mode = last["created_at"], last["mode"]
        else:
            sent, date, mode = "No", "", ""
            if not m["email"] or m["email"] == NOT_FOUND:
                status = "no valid email - DM only"
            elif not m["approved"]:
                status = "awaiting review"
            else:
                status = "ready to send"
        dm_status = dm_logs[0]["status"] if dm_logs else "not queued"
        rows.append([m["name"], m["email"] or NOT_FOUND, "Yes", sent, date, status, mode, dm_status])
    path = folder / "outreach_tracker.csv"
    write_csv(path, ["Influencer", "Email", "Message Generated", "Sent", "Date", "Status", "Mode",
                     "Instagram DM Status"], rows)
    return path


def export_dm_queue(conn, folder):
    """The Instagram DMs a person needs to send by hand."""
    rows = []
    for q in storage.fetch(conn,
            "SELECT i.name, i.instagram, i.profile_url, m.instagram_dm, l.status, l.channel_id FROM outreach_log l "
            "JOIN influencers i ON i.channel_id = l.channel_id JOIN messages m ON m.channel_id = l.channel_id "
            "WHERE l.channel_type = 'instagram_dm'"):
        rows.append([q["name"], q["instagram"] or NOT_FOUND, q["profile_url"], q["instagram_dm"], q["status"], q["channel_id"]])
    path = folder / "dm_queue.csv"
    write_csv(path, ["Influencer", "Instagram Profile", "YouTube Profile", "DM Text", "Status", "Channel ID"], rows)
    return path


def export_log(conn, folder):
    """Every send attempt, in order."""
    rows = []
    for e in storage.fetch(conn, "SELECT l.*, i.name FROM outreach_log l "
                                 "JOIN influencers i ON i.channel_id = l.channel_id ORDER BY l.id"):
        rows.append([e["id"], e["name"], e["channel_type"], e["recipient"], e["mode"], e["status"], e["detail"], e["created_at"]])
    path = folder / "outreach_log.csv"
    write_csv(path, ["ID", "Influencer", "Channel", "Recipient", "Mode", "Status", "Detail", "Timestamp (UTC)"], rows)
    return path


def export_all(cfg, conn):
    folder = cfg["paths"]["data"]
    messages_csv, messages_md = export_messages(conn, folder)
    files = [export_dataset(cfg, conn, folder), export_shortlist(cfg, conn, folder), messages_csv, messages_md,
             export_tracker(conn, folder), export_dm_queue(conn, folder), export_log(conn, folder)]
    log.info("exported %d files to %s", len(files), folder)
    return files


def summary(conn):
    """Counts for every stage, as text."""
    def n(sql, params=()):
        return storage.count(conn, sql, params)

    return "\n".join([
        "Discovered creators      : " + str(n("SELECT COUNT(*) FROM influencers")),
        "  passed filters         : " + str(n("SELECT COUNT(*) FROM influencers WHERE filter_status = 'passed'")),
        "  failed filters         : " + str(n("SELECT COUNT(*) FROM influencers WHERE filter_status = 'failed'")),
        "Shortlisted with email   : " + str(n("SELECT COUNT(*) FROM influencers WHERE filter_status = 'passed' "
                                              "AND email IS NOT NULL AND email != ?", (NOT_FOUND,))),
        "Messages generated       : " + str(n("SELECT COUNT(*) FROM messages")),
        "  written by LLM         : " + str(n("SELECT COUNT(*) FROM messages WHERE generated_by = 'llm'")),
        "  awaiting review        : " + str(n("SELECT COUNT(*) FROM messages WHERE approved = 0")),
        "Emails simulated         : " + str(n("SELECT COUNT(*) FROM outreach_log WHERE channel_type = 'email' AND status = 'simulated'")),
        "Emails sent (test/live)  : " + str(n("SELECT COUNT(*) FROM outreach_log WHERE channel_type = 'email' AND status = 'sent'")),
        "Instagram DMs queued     : " + str(n("SELECT COUNT(*) FROM outreach_log WHERE channel_type = 'instagram_dm'")),
    ])
